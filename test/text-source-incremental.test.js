// @vitest-environment jsdom
import {expect, it} from 'vitest'
import {Schema} from 'prosemirror-model'
import {renderTextSource} from '../example/src/text-source-view.js'
const schema = new Schema({nodes: {doc: {content: 'paragraph+'}, paragraph: {content: 'text*'}, text: {}}, marks: {strong: {}, em: {}, link: {attrs: {href: {}}}}})
const p = children => schema.node('paragraph', null, children)
const t = (text, mark) => schema.text(text, mark ? [schema.mark(mark, mark === 'link' ? {href: 'javascript:literal'} : undefined)] : [])

it('changes one dense text leaf and restores the original nodes without recreating mark wrappers', () => {
  const node = p(Array.from({length: 600}, (_, i) => t(i % 2 ? 'b' : 'a', i % 2 ? 'em' : 'strong')))
  const target = document.createElement('div')
  renderTextSource(target, node)
  const wrappers = [...target.childNodes], leaves = wrappers.map(el => el.firstChild)
  const observer = new MutationObserver(() => {})
  observer.observe(target, {childList: true, subtree: true})
  renderTextSource(target, node, {from: 301, to: 302, start: 1})
  expect([...target.childNodes].every((element, i) => element === wrappers[i])).toBe(true)
  expect(wrappers[299].firstChild).toBe(leaves[299])
  expect(wrappers[301].firstChild).toBe(leaves[301])
  expect(target.querySelectorAll('.selected-text-change')).toHaveLength(1)
  const changes = observer.takeRecords()
  expect(changes).toHaveLength(1)
  expect([...changes[0].removedNodes]).toEqual([leaves[300]])
  expect(changes[0].addedNodes).toHaveLength(1)
  renderTextSource(target, node)
  expect([...target.childNodes].every((element, i) => element === wrappers[i])).toBe(true)
  expect(wrappers.every((el, i) => el.firstChild === leaves[i])).toBe(true)
  expect(observer.takeRecords()).toHaveLength(2)
  renderTextSource(target, node)
  expect(observer.takeRecords()).toHaveLength(0)
  expect(target.textContent).toBe(node.textContent)
  observer.disconnect()
})

it('splits only the containing run for an internal empty marker outside all marks', () => {
  const node = p([t('before', 'em'), t('abcd', 'link'), t('after', 'strong')])
  const target = document.createElement('div')
  renderTextSource(target, node)
  const original = [...target.childNodes], leaf = original[1].firstChild
  const point = renderTextSource(target, node, {from: 9, to: 9, start: 1, label: 'Insertion point'})
  expect(point.parentNode).toBe(target)
  expect(point.previousSibling.textContent).toBe('ab')
  expect(point.nextSibling.textContent).toBe('cd')
  expect(target.firstChild).toBe(original[0])
  expect(target.lastChild).toBe(original[2])
  expect(target.querySelectorAll('[href], a')).toHaveLength(0)
  expect(target.textContent).toBe(node.textContent)
  renderTextSource(target, node)
  expect([...target.childNodes]).toEqual(original)
  expect(target.childNodes[1].firstChild).toBe(leaf)
})

it('invalidates cached sources after replacement and distinguishes equal-text differently marked nodes', () => {
  const a = p(t('same', 'strong')), b = p(t('same', 'em'))
  const target = document.createElement('div')
  renderTextSource(target, a, {from: 1, to: 2, start: 1})
  target.replaceChildren(document.createTextNode('external'))
  renderTextSource(target, a)
  expect(target.textContent).toBe('same')
  expect(target.firstChild.tagName).toBe('STRONG')
  renderTextSource(target, b)
  expect(target.firstChild.tagName).toBe('EM')
  expect(target.querySelectorAll('.selected-text-change')).toHaveLength(0)
  renderTextSource(target, b, {from: 2, to: 2, start: 1, label: 'point'})
  target.replaceChildren()
  renderTextSource(target, b)
  expect(target.textContent).toBe('same')
  expect(target.firstChild.tagName).toBe('EM')
})

it('rebuilds reordered source runs and relocated decorations without stale undo errors', () => {
  const node = p([t('a', 'strong'), t('b', 'em')])
  const target = document.createElement('div')
  renderTextSource(target, node)
  target.append(target.firstChild)
  renderTextSource(target, node)
  expect(target.textContent).toBe('ab')
  expect(target.firstChild.tagName).toBe('STRONG')
  const highlight = renderTextSource(target, node, {from: 1, to: 2, start: 1})
  target.lastChild.append(highlight)
  expect(() => renderTextSource(target, node)).not.toThrow()
  expect(target.textContent).toBe('ab')
  expect(target.firstChild.textContent).toBe('a')
  expect(target.lastChild.textContent).toBe('b')
  expect(target.querySelectorAll('.selected-text-change')).toHaveLength(0)
})
